package com.skydispatch.domain.enums;

/**
 * 空域类型。
 *
 * <p>不同空域对路径规划的影响不同：禁飞区必须完全绕开，走廊区则是"推荐走这里"，
 * 因此用类型而不是一个 noFly 布尔值来建模。
 */
public enum ZoneType {

    /** 禁飞区，任何情况下不得进入。 */
    NO_FLY,

    /** 限飞区，需满足条件（高度/时段/审批）才可进入。 */
    RESTRICTED,

    /** 航路走廊，鼓励通行的低空通道。 */
    CORRIDOR,

    /** 警告区，可通行但需要提示。 */
    WARNING,

    /**
     * 建筑障碍：高楼、塔吊、大型立交等实体障碍物。
     *
     * <p>与"禁飞区"的区别在于语义与高度：建筑障碍的高度由 {@code maxAltitudeM} 表达
     * （例如 180m 高的大楼就是 0~180m 不可穿越），无人机<b>飞过楼顶即可</b>，
     * 而禁飞区通常是"无论多高都不许进"。
     *
     * <p>同样计入路径规划的障碍物，让航线不是简单两点直线，而是绕开楼群。
     */
    BUILDING,

    /**
     * 地形障碍：山体、丘陵、高地等自然地貌。
     *
     * <p>与建筑障碍同样是"低于顶高不可穿越"，区别是底部贴合地面、范围通常更大，
     * 而且在低空高度层规划时必须优先绕开（撞山没有迫降空间）。
     */
    TERRAIN
}
